// ПОКАЗ СЦЕНЫ
// ==========================================================

function showScene(sceneId) {

    const scene = scenes[sceneId];

    if (!scene) {

        console.error(
            "Сцена не найдена:",
            sceneId
        );

        return;
    }


    storyCounter.textContent =
        "СЦЕНА " + sceneNumber;


    storyIcon.textContent =
        scene.icon;


    storyText.innerHTML =
        scene.text;


    choices.innerHTML = "";


    scene.choices
        .filter(choice => {

            if (choice.condition) {
                return choice.condition();
            }

            return true;

        })
        .forEach(choice => {

            const button =
                document.createElement("button");


            button.className =
                "choice-btn";


            button.textContent =
                choice.text;


            button.addEventListener(
                "click",
                function () {

                    if (choice.action) {
                        choice.action();
                    }


                    sceneNumber++;


                    showNext(
                        choice.next
                    );

                }
            );


            choices.appendChild(button);

        });


    updateInventory();


    window.scrollTo({
        top: 0,
        behavior: "smooth"
    });

}


// ==========================================================
// ПЕРЕХОД К СЦЕНЕ / КОНЦОВКЕ
// ==========================================================

function showNext(next) {

    if (next === "endingThrone") {

        showEndingThrone();

        return;
    }


    if (next === "endingHeart") {

        showEndingHeart();

        return;
    }


    if (next === "endingEscape") {

        showEndingEscape();

        return;
    }


    showScene(next);
}


