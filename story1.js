function hasItem(item) {
    return game.items.includes(item);
}


function addItem(item) {

    if (!hasItem(item)) {
        game.items.push(item);
    }

    updateInventory();
}


function removeItem(item) {

    game.items = game.items.filter(
        currentItem => currentItem !== item
    );

    updateInventory();
}


