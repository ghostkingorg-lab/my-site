// ==========================================================
// ОБНОВЛЕНИЕ ИНВЕНТАРЯ
// ==========================================================

function updateInventory() {

    if (!inventoryItems) {
        return;
    }

    if (game.items.length === 0) {

        inventoryItems.innerHTML =
            `<span class="empty-inventory">Пусто</span>`;

        return;
    }


    inventoryItems.innerHTML =
        game.items
            .map(item => `
                <span class="inventory-item">
                    ${itemNames[item] || item}
                </span>
            `)
            .join("");
}


